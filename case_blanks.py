"""
The hand-written blanks for the built-in cases.

Each case here is the same set of blanks that generate_case.py asks the local
model for, but written by hand so that every detail fits its setting.
build_cases.py turns them into the files in cases/ and evals/, using the same
sentence templates and the same checks as the generator.

To add a case: copy one entry, change the blanks, run  python build_cases.py

The first case, The Harbour Light, is not in this file. It was written
directly as cases/harbour_light.json.
"""


def person(name, gender, age, job, about, personality, speaking_style):
    return {"name": name, "gender": gender, "age": age, "job": job, "about_text": about,
            "personality": personality, "speaking_style": speaking_style}


def visitor(name, gender, age, personality, speaking_style):
    about = ("He" if gender == "male" else "She") + " arrived a few days ago"
    return person(name, gender, age, "visitor", about, personality, speaking_style)


